use std::collections::{HashMap, HashSet};
use std::sync::{Arc, Mutex};

#[derive(Clone)]
pub struct DagState {
    pub inputs: HashMap<String, HashMap<String, String>>,
    pub outputs: Arc<Mutex<HashMap<String, String>>>,
    unverified_inputs: HashSet<String>,
}

impl DagState {
    pub fn new(
        inputs: HashMap<String, HashMap<String, String>>,
        unverified_inputs: HashSet<String>,
    ) -> Self {
        Self {
            inputs,
            outputs: Arc::new(Mutex::new(HashMap::new())),
            unverified_inputs,
        }
    }

    /// Reads an input artifact generated by a task in the `needs:` array.
    /// `task_name` is the name of the upstream task that generated the output.
    pub fn get_input(&self, task_name: &str, key: &str) -> Option<String> {
        self.inputs
            .get(task_name)
            .and_then(|outputs| outputs.get(key))
            .cloned()
    }

    /// Sets an output artifact that downstream tasks can consume.
    pub fn set_output(&self, key: &str, value: &str) {
        if let Ok(mut outputs) = self.outputs.lock() {
            outputs.insert(key.to_string(), value.to_string());
        }
    }

    pub fn input_is_unverified(&self, task_name: &str) -> bool {
        self.unverified_inputs.contains(task_name)
    }
}
